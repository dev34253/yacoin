"""Tests of share/qt/extract_strings_qt.py.

The script runs in a temporary directory that holds src/ with one source file
and src/qt/. xgettext is a stub: a shell script that records its arguments,
prints a fixed .po text and exits with a given status. PATH holds only the
stub's directory, and the locale is C, so nothing depends on the host's tools
or locale.

Run: python3 -I -m unittest discover -s contrib/devtools/test
"""

import os
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
SCRIPT = os.path.join(REPO, "share", "qt", "extract_strings_qt.py")
OUT_CPP = os.path.join("src", "qt", "bitcoinstrings.cpp")

STUB = """#!/bin/sh
printf '%s\\n' "$@" > xgettext-args
printf '%s' '{po}'
exit {status}
"""

# A .po text as xgettext prints it: the header entry, a one-line string, a
# string split over several lines, an escaped quote with \n, and a string
# with characters outside ASCII.
PO = r'''# SOME DESCRIPTIVE TITLE.
#, fuzzy
msgid ""
msgstr ""
"Project-Id-Version: PACKAGE VERSION\n"
"Content-Type: text/plain; charset=CHARSET\n"

#: src/example.cpp:1
msgid "Hello world"
msgstr ""

#: src/example.cpp:2
msgid ""
"A long sentence that goes on for longer than one line of the output and is "
"split in two"
msgstr ""

#: src/example.cpp:3
msgid "Say \"hi\"\n"
msgstr ""

#: src/example.cpp:4
msgid "Grüße"
msgstr ""
'''

EXPECTED = (
    b'#include <QtGlobal>\n'
    b'// Automatically generated by extract_strings.py\n'
    b'#ifdef __GNUC__\n'
    b'#define UNUSED __attribute__((unused))\n'
    b'#else\n'
    b'#define UNUSED\n'
    b'#endif\n'
    b'static const char UNUSED *bitcoin_strings[] = {'
    b'QT_TRANSLATE_NOOP("yacoin-core", "Hello world"),\n'
    b'QT_TRANSLATE_NOOP("yacoin-core", ""\n'
    b'"A long sentence that goes on for longer than one line of the output and is "\n'
    b'"split in two"),\n'
    b'QT_TRANSLATE_NOOP("yacoin-core", "Say \\"hi\\"\\n"),\n'
    b'QT_TRANSLATE_NOOP("yacoin-core", "Gr\xc3\xbc\xc3\x9fe"),\n'
    b'};'
)

EXISTING = b"existing content\n"


def make_tree(root, po=PO, status=0, stub=True):
    """Creates src/, src/qt/ and bin/ under root; bin/ holds the xgettext
    stub when stub is true. Returns the directory for PATH."""
    os.makedirs(os.path.join(root, "src", "qt"))
    with open(os.path.join(root, "src", "example.cpp"), "w", encoding="utf8") as f:
        f.write('const char* s = _("Hello world");\n')
    bindir = os.path.join(root, "bin")
    os.mkdir(bindir)
    if stub:
        assert "'" not in po
        path = os.path.join(bindir, "xgettext")
        with open(path, "w", encoding="utf8") as f:
            f.write(STUB.format(po=po, status=status))
        os.chmod(path, 0o755)
    return bindir


def run_script(root, bindir, interpreter, script=SCRIPT):
    env = {"PATH": bindir, "LC_ALL": "C", "PYTHONUTF8": "0"}
    return subprocess.run([interpreter, "-B", script], cwd=root, env=env,
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE)


class ExtractStringsTest(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.dir = self._tmp.name
        self.out = os.path.join(self.dir, OUT_CPP)

    def tearDown(self):
        self._tmp.cleanup()

    def run_script(self, existing=False, **kwargs):
        bindir = make_tree(self.dir, **kwargs)
        if existing:
            with open(self.out, "wb") as f:
                f.write(EXISTING)
        return run_script(self.dir, bindir, sys.executable)

    def read_out(self):
        with open(self.out, "rb") as f:
            return f.read()

    def assertXgettextError(self, result):
        self.assertNotEqual(result.returncode, 0)
        lines = result.stderr.decode("utf8", "replace").splitlines()
        self.assertEqual(len(lines), 1, lines)
        self.assertIn("xgettext", lines[0])


class OutputTest(ExtractStringsTest):
    def test_writes_expected_bytes(self):
        result = self.run_script()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stderr, b"")
        self.assertEqual(self.read_out(), EXPECTED)

    def test_runs_xgettext_on_the_sources(self):
        result = self.run_script()
        self.assertEqual(result.returncode, 0, result.stderr)
        with open(os.path.join(self.dir, "xgettext-args"), encoding="utf8") as f:
            args = f.read().splitlines()
        self.assertEqual(args, ["--output=-", "-n", "--keyword=_", "src/example.cpp"])

    def test_replaces_existing_output(self):
        result = self.run_script(existing=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.read_out(), EXPECTED)


class XgettextMissingTest(ExtractStringsTest):
    def test_no_output_file(self):
        result = self.run_script(stub=False)
        self.assertXgettextError(result)
        self.assertFalse(os.path.exists(self.out))

    def test_existing_output_unchanged(self):
        result = self.run_script(existing=True, stub=False)
        self.assertXgettextError(result)
        self.assertEqual(self.read_out(), EXISTING)


class XgettextFailsTest(ExtractStringsTest):
    def test_no_output_file(self):
        result = self.run_script(status=1)
        self.assertXgettextError(result)
        self.assertFalse(os.path.exists(self.out))

    def test_existing_output_unchanged(self):
        result = self.run_script(existing=True, status=1)
        self.assertXgettextError(result)
        self.assertEqual(self.read_out(), EXISTING)


if __name__ == "__main__":
    unittest.main()
